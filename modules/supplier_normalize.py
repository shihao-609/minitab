_ALIAS_CACHE = None


def _clean(v):
    """转字符串并去首尾空白，NaN/None → ''"""
    if v is None:
        return ''
    try:
        if math.isnan(float(v)):
            return ''
    except (TypeError, ValueError):
        pass
    return str(v).strip()


def _load_aliases():
    """从数据库读取别名映射 {别名: 规范名}，会话级缓存；失败时返回空表不影响规则。"""
    global _ALIAS_CACHE
    if _ALIAS_CACHE is not None:
        return _ALIAS_CACHE
    aliases = {}
    try:
        for r in supabase_helper.list_supplier_aliases():
            a = _clean(r.get('alias'))
            c = _clean(r.get('canonical'))
            if a and c:
                aliases[a] = c
    except Exception:
        aliases = {}
    _ALIAS_CACHE = aliases
    return aliases


def reload_aliases():
    """强制重新加载别名表（页面新增/删除别名后调用）。"""
    global _ALIAS_CACHE
    _ALIAS_CACHE = None


def _strip_region(name):
    """循环剥离行政区划前缀（省/市/区/县）与常见城市名，直到无变化。"""
    while True:
        before = name
        m = _REGION_SUFFIX_RE.match(name)
        if m:
            name = name[m.end():]
        name = re.sub(r'^[省市县区旗州镇]', '', name)
        m = _CITY_RE.match(name)
        if m:
            name = name[m.end():]
        if name == before:
            break
    return name


def _strip_suffix(name):
    for sfx in _COMPANY_SUFFIXES:
        if name.endswith(sfx) and len(name) > len(sfx):
            return name[:-len(sfx)]
    return name


def normalize_supplier(name):
    """返回供应商规范核心名；别名优先，其次规则剥离。"""
    raw = _clean(name)
    if not raw:
        return ''
    aliases = _load_aliases()
    if raw in aliases:
        return aliases[raw]

    s = _strip_region(raw)          # 去省市区前缀
    s = _strip_suffix(s)            # 去公司后缀
    s = re.sub(r'\s+', '', s)       # 去空白
    s = re.sub(r'[（(].*?[）)]', '', s)  # 去括号内容
    # 二次剥离：如 "常州市塑邦模型有限公司" 先去 "常州市" 再去后缀
    s2 = _strip_region(s)
    if s2 != s:
        s = _strip_suffix(s2)
    return s


def same_supplier(a, b):
    """判断两个供应商名称是否指向同一公司。"""
    a = _clean(a)
    b = _clean(b)
    if not a or not b:
        return a == b
    if a == b:
        return True
    na, nb = normalize_supplier(a), normalize_supplier(b)
    if not na or not nb:
        return False
    if na == nb:
        return True
    # 核心名互为包含兜底（短核心名 ≥ 2 字，长度差 ≤ 8）
    short, long = (na, nb) if len(na) <= len(nb) else (nb, na)
    if len(short) >= 2 and short in long and len(long) - len(short) <= 8:
        return True
    return False
